// 1. 'number' + 3 + 3
// Результат: "number33"
// Крок 1: 'number' + 3 -> рядок + число = конкатенація ("number3").
// Крок 2: "number3" + 3 -> рядок + число = конкатенація ("number33").

// 2. null + 3
// Результат: 3
// Крок 1: null при математичних операціях перетворюється на 0.
// Крок 2: 0 + 3 = 3.

// 3. 5 && "qwerty"
// Результат: "qwerty"
// Крок 1: Оператор && (І) повертає останнє істинне значення, якщо обидва операнди істинні.
// Крок 2: 5 — істинне (truthy), переходимо до другого значення. "qwerty" повертається.

// 4. +'40' + +'2' + "hillel"
// Результат: "42hillel"
// Крок 1: +'40' перетворює рядок на число 40.
// Крок 2: +'2' перетворює рядок на число 2.
// Крок 3: 40 + 2 = 42.
// Крок 4: 42 + "hillel" -> число + рядок = конкатенація "42hillel".

// 5. '10' - 5 === 6
// Результат: false
// Крок 1: При відніманні '10' перетворюється на число 10.
// Крок 2: 10 - 5 = 5.
// Крок 3: Порівняння 5 === 6 повертає false.

// 6. true + false
// Результат: 1
// Крок 1: true перетворюється на 1, false — на 0.
// Крок 2: 1 + 0 = 1.

// 7. '4px' - 3
// Результат: NaN
// Крок 1: При спробі відняти рядок '4px' намагається стати числом, але містить букви.
// Крок 2: Перетворення дає NaN (Not a Number). NaN - 3 = NaN.

// 8. '4' - 3
// Результат: 1
// Крок 1: При відніманні рядок '4' автоматично стає числом 4.
// Крок 2: 4 - 3 = 1.

// 9. '6' + 3 ** 0
// Результат: "61"
// Крок 1: Пріоритет у піднесення до степеня. 3 ** 0 = 1.
// Крок 2: '6' + 1 -> рядок + число = конкатенація "61".

// 10. 12 / '6'
// Результат: 2
// Крок 1: При діленні рядок '6' перетворюється на число 6.
// Крок 2: 12 / 6 = 2.

// 11. '10' + (5 === 6)
// Результат: "10false"
// Крок 1: У дужках 5 === 6 дає булеве значення false.
// Крок 2: '10' + false -> рядок + булеве значення = конкатенація "10false".

// 12. null == ''
// Результат: false
// Крок 1: null дорівнює лише undefined при нестрогому порівнянні. Рядок не є винятком.

// 13. 3 ** (9 / 3)
// Результат: 27
// Крок 1: У дужках 9 / 3 = 3.
// Крок 2: 3 ** 3 (3 в кубі) = 27.

// 14. !!'false' == !!'true'
// Результат: true
// Крок 1: !! перетворює будь-який непустий рядок на true.
// Крок 2: !!'false' -> true. !!'true' -> true.
// Крок 3: true == true -> результат true.

// 15. 0 || '0' && 1
// Результат: 1
// Крок 1: Пріоритет у &&. '0' — це істинний рядок (непустий), тому повертається друге значення: 1.
// Крок 2: 0 || 1 -> оператор || повертає перше істинне значення. Результат 1.

// 16. (+null == false) < 1
// Результат: false
// Крок 1: +null стає 0.
// Крок 2: 0 == false -> true (бо 0 і false рівні при нестрогому порівнянні).
// Крок 3: true < 1 -> true перетворюється на 1. 1 < 1 повертає false.

// 17. false && true || true
// Результат: true
// Крок 1: false && true повертає false.
// Крок 2: false || true повертає true.

// 18. false && (false || true)
// Результат: false
// Крок 1: У дужках false || true повертає true.
// Крок 2: false && true повертає false.

